/* ibm-1: the rhythm catalogue, drawn as a table under the resonance tiles.

   EVERY ROW IS BUILT FROM window.IBM_RHYTHMS AT RUNTIME.  nothing here is typed
   out: not a band, not a peak, not a station, not a count.  data/rhythms.js is
   generated by scripts/export_rhythms.py from ibm/rhythms.py, so the table on the
   page and the table the trainer scores are the same table, and a rhythm added or
   a band widened in the catalogue appears here without anyone editing this file.
   the eleven 3-D tiles above are hand-written prose and CAN drift; this cannot.

   three things this file is not allowed to do:

   1. PUT PROVENANCE IN THE VISIBLE TEXT.  each rhythm carries `evidence`
      (measured-here / measurable-now / literature / target) and `substrate`
      (expressible / needs-thalamus / ...).  both go on the row's data-status
      attribute and nowhere else -- no badge, no caption, no asterisk -- the same
      arrangement the tiles above use, for the same reason (index.html's comment
      over the section, and docs/LOG.md).  the visible table states the end state.
   2. PRINT A NUMBER THE CATALOGUE DOES NOT HAVE.  a null band or a null peak is
      an em dash, never a guess and never an empty cell that reads as zero.  a
      band is a DECLARED consequence of a ring with a delay -- it is not a
      measurement of this model, and no column here implies it is one.
   3. RESHAPE A NUMBER.  a frequency is printed as the catalogue stores it; the
      only transform is the unit convention below, which is reversible and is
      repeated verbatim in the title attribute of every cell it touches.

   THE UNIT CONVENTION, one rule, applied everywhere: at or above 0.5 Hz a
   rhythm is printed in Hz ("8-13 Hz"); below 0.5 Hz it is printed as a PERIOD
   ("24 h", "90 min", "18-22 s"), because 1.16e-05 Hz is not a quantity a reader
   can hold.  the Hz form is kept on the cell's title so nothing is lost.  the
   two ends of a band swap when it is inverted -- the LOW frequency is the LONG
   period -- and the unit is chosen from the longer end so a range never mixes
   units.

   layout: the row folds to a stacked block on a narrow container and opens into
   columns on a wide one, and the query is a @container query on the table's own
   width, never an @media query on the viewport's.  this element sits inside a
   station whose width has not tracked the viewport's (CLAUDE.md, "The site": the
   retrieval panel was 387px at a 1400px viewport and 856px at 900px).  the base
   styles are the NARROW ones, so a browser without container queries gets the
   stacked block, which is readable at any width. */
(function () {
  "use strict";

  const host = document.getElementById("rhythm-table");
  const D = window.IBM_RHYTHMS;
  if (!host || !D || !D.loops || !D.rhythms) return;

  const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

  /* ---- numbers ------------------------------------------------------- */

  /* a frequency in Hz, to at most two decimals, trailing zeros stripped.  13.45
     stays 13.45: the spindle tile above prints that figure and a table rounding
     it to 13.5 beside the tile that says 13.45 reads as two different results. */
  const hz = (v) => String(Number(v.toFixed(Math.abs(v) >= 100 ? 0 : 2)));
  /* a period, to about two significant figures -- 18.18 s is spurious precision
     on a band whose ends are 0.045 and 0.055 */
  const per = (v) => String(Number(v.toFixed(Math.abs(v) >= 10 ? 0 : 1)));

  const SLOW = 0.5;                     // below this, print the period
  const MINUTE = 120, HOUR = 10800;     // seconds; thresholds, not exact folds

  function unitOf(seconds) {
    if (seconds < MINUTE) return { d: 1, u: "s" };
    if (seconds < HOUR) return { d: 60, u: "min" };
    return { d: 3600, u: "h" };
  }

  /* the Hz form kept on the title attribute is the catalogue's own number, NOT a
     rounded one: hz() at two decimals turns 0.045 into 0.04 and 1.16e-05 into 0,
     and a tooltip that disagrees with ibm/rhythms.py is worse than no tooltip. */
  const exact = (v) => (v >= SLOW ? hz(v) : String(v));

  /* a band [lo, hi] in Hz -> {text, title}.  null -> null. */
  function fmtBand(b) {
    if (!b || b.length !== 2) return null;
    const [lo, hi] = b;
    const raw = exact(lo) + "–" + exact(hi) + " Hz";
    if (lo >= SLOW) return { text: raw, title: "" };
    const tLong = 1 / lo, tShort = 1 / hi;          // low frequency, long period
    const { d, u } = unitOf(tLong);
    return { text: per(tShort / d) + "–" + per(tLong / d) + " " + u, title: raw };
  }

  /* a single frequency in Hz -> {text, title}.  null -> null. */
  function fmtPeak(p) {
    if (p === null || p === undefined) return null;
    const raw = exact(p) + " Hz";
    if (p >= SLOW) return { text: raw, title: "" };
    const t = 1 / p;
    const { d, u } = unitOf(t);
    return { text: per(t / d) + " " + u, title: raw };
  }

  /* a round trip [lo, hi] in ms.  the catalogue's slowest ring is 536 ms, so
     this stays in ms; if one ever runs into seconds the period rule above is
     the one to reuse. */
  function fmtTrip(t) {
    if (!t || t.length !== 2) return "";
    return per(t[0]) + "–" + per(t[1]) + " ms";
  }

  const prettyState = (s) =>
    s.replace(/^nrem(\d)$/, "NREM $1").replace(/^rem$/, "REM").replace(/-/g, " ");

  /* ---- the behavioural-state chips ------------------------------------
     the vocabulary is whatever the catalogue uses, so the families are matched
     against the states PRESENT rather than declared ahead of them: a family with
     no rhythms in it never appears, and a state no family claims gets a chip of
     its own rather than being silently unreachable.  a rhythm whose states are
     ["all"] is in every state and therefore passes every chip. */
  const FAMILIES = [
    { key: "wake", label: "wake", re: /^(wake|wake-.+|quiet-wake)$/ },
    { key: "sleep", label: "sleep", re: /^(sleep|nrem\d|rem|anaesthesia)$/ },
    { key: "task", label: "task", re: /^(wake-task|encoding|retrieval|working-memory|listening|exploration)$/ },
    { key: "movement", label: "movement", re: /^(movement|movement-imagery|action-observation|locomotion|posture|hold|.+-contraction|sniffing)$/ },
    { key: "affect", label: "reward & threat", re: /^(reward|threat)$/ },
  ];
  const EVERY = "all";   // the catalogue's own token for "in every state"

  function familiesFor(state) {
    /* "all" is not a behavioural state, it is every one of them -- given a chip
       of its own it would sit beside the reset chip, with the same word on it,
       showing one row. */
    if (state === EVERY) return [];
    const hit = FAMILIES.filter((f) => f.re.test(state)).map((f) => f.key);
    return hit.length ? hit : ["s:" + state];      // its own chip
  }

  /* ---- build ---------------------------------------------------------- */

  const byLoop = new Map();
  D.rhythms.forEach((r) => {
    if (!byLoop.has(r.loop)) byLoop.set(r.loop, []);
    byLoop.get(r.loop).push(r);
  });

  const chipMeta = new Map();            // key -> {key, label, n}
  const rows = [];                       // {el, find, fams:Set, every:bool}
  const loops = [];                      // {el, rows:[]}

  function chipLabel(key) {
    const f = FAMILIES.find((x) => x.key === key);
    return f ? f.label : prettyState(key.slice(2));
  }

  let html = "";
  D.loops.forEach((L) => {
    const ring = L.ring.map((s) => s.name);
    const ringHtml =
      ring.map((n) => '<span class="rzt-stn">' + esc(n) + "</span>").join('<i class="rzt-arw" aria-hidden="true">→</i>') +
      '<i class="rzt-arw" aria-hidden="true">→</i><span class="rzt-stn rzt-back">' + esc(ring[0]) + "</span>";

    let rowsHtml = "";
    (byLoop.get(L.id) || []).forEach((r) => {
      const band = fmtBand(r.band);
      const peak = fmtPeak(r.peak);
      const states = r.states.map(prettyState).join(" · ");
      const cell = (cls, v) =>
        v
          ? '<span class="' + cls + '"' + (v.title ? ' title="' + esc(v.title) + '"' : "") + ">" + esc(v.text) + "</span>"
          : '<span class="' + cls + ' rzt-nil" aria-label="none">—</span>';
      /* data-status carries evidence and substrate, and is the ONLY place either
         of them appears.  do not promote one of these into the row's text. */
      rowsHtml +=
        '<details class="rzt-row" data-rhythm="' + esc(r.id) + '" data-status="' + esc(r.evidence + " " + r.substrate) + '">' +
        '<summary class="rzt-sum">' +
        '<span class="rzt-name">' + esc(r.name) + "</span>" +
        cell("rzt-band", band) +
        cell("rzt-peak", peak) +
        '<span class="rzt-st">' + esc(states) + "</span>" +
        "</summary>" +
        '<p class="rzt-mech">' + esc(r.mechanism) + "</p>" +
        "</details>";
    });

    html +=
      '<section class="rzt-loop" data-loop="' + esc(L.id) + '">' +
      '<h4 class="rzt-lh">' +
      '<span class="rzt-lname">' + esc(L.name) + "</span>" +
      '<span class="rzt-ring">' + ringHtml + "</span>" +
      '<span class="rzt-trip">' + esc(fmtTrip(L.round_trip_ms)) + "</span>" +
      "</h4>" +
      '<div class="rzt-rows">' + rowsHtml + "</div>" +
      "</section>";
  });

  host.innerHTML =
    '<div class="rzt-bar">' +
    '<div class="rzt-chips" role="group" aria-label="narrow by behavioural state"></div>' +
    '<label class="rzt-find"><span class="rzt-sr">search the rhythms</span>' +
    '<input type="search" class="rzt-q" placeholder="rhythm, loop or structure" autocomplete="off" spellcheck="false"></label>' +
    "</div>" +
    '<div class="rzt-colhead" aria-hidden="true"><span>rhythm</span><span>band</span><span>peak</span><span>states</span></div>' +
    '<div class="rzt-body">' + html + "</div>" +
    '<p class="rzt-none" hidden>Nothing matches. Clear the filters to see all of them.</p>' +
    '<p class="rzt-count" aria-live="polite"></p>';

  /* ---- index the rows we just wrote ----------------------------------- */

  host.querySelectorAll(".rzt-loop").forEach((sec) => {
    const L = D.loops.find((x) => x.id === sec.dataset.loop);
    const entry = { el: sec, rows: [] };
    sec.querySelectorAll(".rzt-row").forEach((el) => {
      const r = D.rhythms.find((x) => x.id === el.dataset.rhythm);
      const fams = new Set();
      r.states.forEach((s) => familiesFor(s).forEach((f) => fams.add(f)));
      const band = fmtBand(r.band), peak = fmtPeak(r.peak);
      const row = {
        el,
        fams,
        every: r.states.indexOf(EVERY) !== -1,
        /* everything a reader might type, lowercased once: the rhythm, its loop,
           the loop's stations, the states, the mechanism and both printed
           numbers.  evidence and substrate are deliberately NOT in here -- they
           are status, and status is not visible copy on this page. */
        find: [
          r.name, r.id, L.name, L.id,
          L.ring.map((s) => s.name + " " + s.station).join(" "),
          r.states.map(prettyState).join(" "), r.states.join(" "),
          r.mechanism,
          band ? band.text + " " + band.title : "",
          peak ? peak.text + " " + peak.title : "",
        ].join(" ").toLowerCase(),
      };
      entry.rows.push(row);
      rows.push(row);
      row.fams.forEach((f) => {
        if (!chipMeta.has(f)) chipMeta.set(f, { key: f, label: chipLabel(f), n: 0 });
      });
    });
    loops.push(entry);
  });

  /* a chip's count is the rhythms it would show, which includes every
     all-states rhythm -- the number under the chip and the number the chip
     produces are the same number. */
  chipMeta.forEach((m) => {
    m.n = rows.filter((row) => row.every || row.fams.has(m.key)).length;
  });
  const order = FAMILIES.map((f) => f.key).filter((k) => chipMeta.has(k))
    .concat([...chipMeta.keys()].filter((k) => k.indexOf("s:") === 0)
      .sort((a, b) => chipMeta.get(b).n - chipMeta.get(a).n || a.localeCompare(b)));

  const chipBox = host.querySelector(".rzt-chips");
  chipBox.innerHTML =
    '<button type="button" class="rzt-chip is-on" data-fam="" aria-pressed="true">all<i>' + rows.length + "</i></button>" +
    order.map((k) => {
      const m = chipMeta.get(k);
      return '<button type="button" class="rzt-chip" data-fam="' + esc(k) + '" aria-pressed="false">' +
        esc(m.label) + "<i>" + m.n + "</i></button>";
    }).join("");

  /* ---- filtering: pure DOM, no rebuild -------------------------------- */

  const active = new Set();
  const qEl = host.querySelector(".rzt-q");
  const noneEl = host.querySelector(".rzt-none");
  const countEl = host.querySelector(".rzt-count");
  const TOTAL = rows.length, NLOOPS = loops.length;

  function apply() {
    const q = qEl.value.trim().toLowerCase();
    let shown = 0, shownLoops = 0;
    loops.forEach((L) => {
      let n = 0;
      L.rows.forEach((row) => {
        const byState = active.size === 0 || row.every || [...active].some((f) => row.fams.has(f));
        const ok = byState && (q === "" || row.find.indexOf(q) !== -1);
        row.el.hidden = !ok;
        if (ok) n++;
      });
      L.el.hidden = n === 0;
      if (n) shownLoops++;
      shown += n;
    });
    noneEl.hidden = shown !== 0;
    countEl.textContent =
      shown === TOTAL
        ? TOTAL + " rhythms · " + NLOOPS + " loops"
        : shown + " of " + TOTAL + " rhythms · " + shownLoops + " of " + NLOOPS + " loops";
    host.classList.toggle("is-empty", shown === 0);
  }

  chipBox.addEventListener("click", (e) => {
    const b = e.target.closest(".rzt-chip");
    if (!b) return;
    const k = b.dataset.fam;
    if (k === "") active.clear();
    else if (active.has(k)) active.delete(k);
    else active.add(k);
    chipBox.querySelectorAll(".rzt-chip").forEach((c) => {
      const on = c.dataset.fam === "" ? active.size === 0 : active.has(c.dataset.fam);
      c.classList.toggle("is-on", on);
      c.setAttribute("aria-pressed", on ? "true" : "false");
    });
    apply();
  });
  qEl.addEventListener("input", apply);

  apply();

  /* a handle for the checks: the page can be asked what it drew rather than
     having the numbers read off a screenshot. */
  window.IBM_RHYTHM_TABLE = {
    rows: TOTAL, loops: NLOOPS,
    visible: () => host.querySelectorAll(".rzt-row:not([hidden])").length,
    fmtBand, fmtPeak, apply,
  };
})();
